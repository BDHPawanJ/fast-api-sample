"""Locust load testing scenarios for FastAPI sample endpoints."""

from uuid import uuid4

from locust import HttpUser, between, task


class FastAPILoadUser(HttpUser):
    """Simulated API user covering public and authenticated flows."""

    wait_time = between(1, 3)

    def on_start(self) -> None:
        """Create a dedicated user for this Locust user and authenticate once."""
        self.email = f"locust-{uuid4().hex}@example.com"
        self.password = "LocustPass123"
        self.access_token = None
        self.last_product_id = None
        self.last_product_etag = None
        self.register_user()
        self.login_user()

    def auth_headers(self) -> dict[str, str]:
        """Return bearer authorization header when token is available."""
        if not self.access_token:
            return {}
        return {"Authorization": f"Bearer {self.access_token}"}

    def register_user(self) -> None:
        """Register current Locust user credentials."""
        payload = {"email": self.email, "password": self.password}
        headers = {"Idempotency-Key": str(uuid4())}
        self.client.post(
            "/v1/auth/register",
            json=payload,
            headers=headers,
            name="POST /v1/auth/register",
        )

    def login_user(self) -> None:
        """Authenticate and store bearer token for protected endpoints."""
        payload = {"email": self.email, "password": self.password}
        with self.client.post(
            "/v1/auth/login",
            json=payload,
            name="POST /v1/auth/login",
            catch_response=True,
        ) as response:
            if response.status_code == 200:
                token = response.json().get("access_token")
                if token:
                    self.access_token = token
                    response.success()
                else:
                    response.failure("Missing access token in login response")
            else:
                response.failure(f"Login failed with status {response.status_code}")

    @task(4)
    def list_products(self) -> None:
        """Exercise cursor-paginated product listing."""
        with self.client.get(
            "/v1/products?limit=10",
            name="GET /v1/products",
            catch_response=True,
        ) as response:
            if response.status_code != 200:
                response.failure(
                    f"List products failed with status {response.status_code}"
                )
                return
            items = response.json().get("items", [])
            if items and not self.last_product_id:
                self.last_product_id = items[0].get("product_id")
            response.success()

    @task(2)
    def get_product(self) -> None:
        """Exercise single-product retrieval for discovered product IDs."""
        if not self.last_product_id:
            self.list_products()
            if not self.last_product_id:
                return
        with self.client.get(
            f"/v1/products/{self.last_product_id}",
            name="GET /v1/products/{product_id}",
            catch_response=True,
        ) as response:
            if response.status_code == 200:
                self.last_product_etag = response.headers.get("ETag")
                response.success()
            else:
                response.failure(f"Get product failed with status {response.status_code}")

    @task(1)
    def create_product(self) -> None:
        """Exercise authenticated product creation."""
        if not self.access_token:
            self.login_user()
            if not self.access_token:
                return
        payload = {
            "name": f"Locust Product {uuid4().hex[:8]}",
            "description": "Generated by Locust load test",
            "price": 99.99,
            "stock": 10,
        }
        headers = self.auth_headers() | {"Idempotency-Key": str(uuid4())}
        with self.client.post(
            "/v1/products",
            json=payload,
            headers=headers,
            name="POST /v1/products",
            catch_response=True,
        ) as response:
            if response.status_code == 201:
                self.last_product_id = response.json().get("product_id")
                self.last_product_etag = None
                response.success()
            else:
                response.failure(
                    f"Create product failed with status {response.status_code}"
                )

    @task(1)
    def patch_product(self) -> None:
        """Exercise authenticated product partial update with ETag precondition."""
        if not self.access_token:
            self.login_user()
            if not self.access_token:
                return
        if not self.last_product_id:
            self.create_product()
            if not self.last_product_id:
                return
        if not self.last_product_etag:
            self.get_product()
            if not self.last_product_etag:
                return

        payload = {"price": 89.99}
        headers = self.auth_headers() | {"If-Match": self.last_product_etag}
        with self.client.patch(
            f"/v1/products/{self.last_product_id}",
            json=payload,
            headers=headers,
            name="PATCH /v1/products/{product_id}",
            catch_response=True,
        ) as response:
            if response.status_code == 200:
                self.last_product_etag = response.headers.get("ETag")
                response.success()
            else:
                response.failure(
                    f"Patch product failed with status {response.status_code}"
                )

    @task(1)
    def delete_product(self) -> None:
        """Exercise authenticated product deletion for user-created products."""
        if not self.access_token:
            self.login_user()
            if not self.access_token:
                return
        if not self.last_product_id:
            return
        with self.client.delete(
            f"/v1/products/{self.last_product_id}",
            headers=self.auth_headers(),
            name="DELETE /v1/products/{product_id}",
            catch_response=True,
        ) as response:
            if response.status_code == 204:
                self.last_product_id = None
                self.last_product_etag = None
                response.success()
            else:
                response.failure(
                    f"Delete product failed with status {response.status_code}"
                )

    @task(1)
    def me(self) -> None:
        """Exercise authenticated current-user endpoint."""
        if not self.access_token:
            self.login_user()
            if not self.access_token:
                return
        self.client.get("/v1/auth/me", headers=self.auth_headers(), name="GET /v1/auth/me")

    @task(2)
    def health_check(self) -> None:
        """Exercise basic health endpoint."""
        self.client.get("/v1/health", name="GET /v1/health")

    @task(1)
    def health_db(self) -> None:
        """Exercise database health endpoint."""
        self.client.get("/v1/health/db", name="GET /v1/health/db")

    @task(1)
    def health_detailed(self) -> None:
        """Exercise detailed health endpoint."""
        self.client.get("/v1/health/detailed", name="GET /v1/health/detailed")

    @task(1)
    def root(self) -> None:
        """Exercise service root endpoint."""
        self.client.get("/", name="GET /")
